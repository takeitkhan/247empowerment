<h2>Overview</h2>
<p>As a meeting organizer, you have full control over who participates in your meetings and what they can do. This guide covers how to manage attendees before, during, and after your meetings.</p>

<div class="guides-info-box">
    <strong>💡 Tip:</strong> Only meeting organizers and co-hosts can manage participants. Regular attendees can see the participant list but cannot remove others.
</div>

<h2>Before the Meeting: Inviting Participants</h2>

<h3>Add Participants When Creating a Meeting</h3>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Open the Participants Section</h4>
        <p>When creating a new meeting, find the "Add Participants" or "Invitees" section in the form.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Enter Email Addresses</h4>
        <p>Type or paste email addresses of people you want to invite. You can add multiple addresses separated by commas.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Set Participant Roles</h4>
        <p>Choose role for each participant:</p>
        <ul>
            <li><strong>Co-Host:</strong> Can manage other participants, mute/unmute, etc.</li>
            <li><strong>Presenter:</strong> Can share screen and present</li>
            <li><strong>Attendee:</strong> Can join and view but not present</li>
        </ul>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">4</div>
    <div class="guides-step-content">
        <h4>Send Invitations</h4>
        <p>When you save the meeting, invitations are automatically sent to all participants with the meeting link and details.</p>
    </div>
</div>

<h3>Add Participants to Existing Meetings</h3>
<ol>
    <li>Open the meeting details</li>
    <li>Click "Edit Meeting"</li>
    <li>Add new participants in the Participants section</li>
    <li>Save changes to send new invitations</li>
</ol>

<h2>During the Meeting: Managing Participants</h2>

<h3>View Participant List</h3>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Click the Participants Button</h4>
        <p>Look for the "Participants" icon in the meeting toolbar (usually shows as a people icon).</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>View the List</h4>
        <p>A panel will open showing everyone currently in the meeting, plus their status (camera on/off, muted/unmuted).</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Access Participant Options</h4>
        <p>Hover over or right-click a participant's name to see available actions (if you're the organizer).</p>
    </div>
</div>

<h3>Mute/Unmute Participants</h3>
<ul>
    <li><strong>Mute Individual:</strong> Click the microphone icon next to a participant to mute their audio</li>
    <li><strong>Mute All:</strong> Use "Mute All" button to silence everyone except yourself</li>
    <li><strong>Unmute:</strong> Click again to allow them to speak</li>
    <li><strong>Note:</strong> Participants can usually unmute themselves unless you lock audio</li>
</ul>

<div class="guides-info-box">
    <strong>💡 Tip:</strong> In large meetings, use "Mute All" to reduce background noise, then let people unmute when they need to speak.
</div>

<h3>Control Participant Video</h3>
<ul>
    <li><strong>Stop Participant Video:</strong> Click the camera icon to turn off someone's video</li>
    <li><strong>Require Video:</strong> Some organizers require video to be on for active participation</li>
    <li><strong>Video Permission:</strong> You can restrict video permissions at meeting start</li>
</ul>

<h3>Spotlight a Participant</h3>
<p>Make one participant's video prominent for everyone to see:</p>
<ol>
    <li>Find the participant in the list</li>
    <li>Look for "Spotlight" or "Make Host Video" option</li>
    <li>Click it to make their video the main view</li>
    <li>Click again to remove spotlight</li>
</ol>

<h3>Grant Screen Sharing Permission</h3>
<ul>
    <li>By default, only organizers/presenters can share screens</li>
    <li>To allow an attendee to share: Find them in participant list</li>
    <li>Look for "Make Presenter" or "Allow Screen Share" option</li>
    <li>Click to grant them sharing rights</li>
</ul>

<h3>Lock/Unlock Participant Controls</h3>
<p>Lock participants to prevent them from taking actions:</p>
<ul>
    <li><strong>Lock Audio:</strong> No one can unmute themselves</li>
    <li><strong>Lock Video:</strong> No one can turn on their camera</li>
    <li><strong>Lock Screen Sharing:</strong> Only organizer can share screens</li>
    <li><strong>Lock Chat:</strong> Prevent all chat messaging</li>
</ul>

<h3>Remove a Participant</h3>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Find the Participant</h4>
        <p>Locate the person you want to remove in the participant list.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Right-Click or Hover</h4>
        <p>Right-click their name or hover over it to reveal the menu options.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Click "Remove" or "Remove Participant"</h4>
        <p>Select the remove option. They will be disconnected from the meeting immediately.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">4</div>
    <div class="guides-step-content">
        <h4>Confirm Removal</h4>
        <p>A confirmation dialog may appear. Click "Yes" or "Remove" to confirm.</p>
    </div>
</div>

<div class="guides-warning-box">
    <strong>⚠️ Note:</strong> Removed participants can rejoin using the original meeting link (unless you disable this).
</div>

<h2>After the Meeting: Attendee Analytics</h2>

<h3>View Meeting Attendance Report</h3>
<ol>
    <li>Go to "Upcoming Meetings & Events" after the meeting ends</li>
    <li>Find the meeting in your list</li>
    <li>Click "View Details" or "Attendance Report"</li>
    <li>See a list of who joined and for how long</li>
</ol>

<h3>Access Attendance Data</h3>
<ul>
    <li><strong>Join Time:</strong> When each participant joined</li>
    <li><strong>Duration:</strong> How long they stayed in the meeting</li>
    <li><strong>Participation:</strong> Whether they had camera/microphone on</li>
    <li><strong>Screen Share Time:</strong> If/when they shared their screen</li>
</ul>

<h3>Export Attendee List</h3>
<ol>
    <li>Open the meeting details after it ends</li>
    <li>Look for "Export" or "Download Report" button</li>
    <li>Choose CSV or PDF format</li>
    <li>The file will include all attendee information and timestamps</li>
</ol>

<h2>Managing Co-Hosts</h2>

<h3>Assign a Co-Host</h3>
<p>Co-hosts have the same permissions as organizers:</p>
<ol>
    <li>Click on a participant in the participant list</li>
    <li>Look for "Make Co-Host" option</li>
    <li>Click to promote them</li>
    <li>They'll now have organizer permissions</li>
</ol>

<h3>Remove Co-Host Permissions</h3>
<ol>
    <li>Right-click the co-host's name</li>
    <li>Select "Make Attendee" or "Remove Co-Host"</li>
    <li>They'll revert to regular attendee status</li>
</ol>

<h2>Advanced Participant Management</h2>

<h3>Waiting Room</h3>
<p>Enable a waiting room to manually approve who enters the meeting:</p>
<ul>
    <li>Enable "Waiting Room" when creating the meeting</li>
    <li>Participants will wait in a lobby until approved</li>
    <li>You'll see a notification when someone is waiting</li>
    <li>Click "Admit" to let them in or "Deny" to reject them</li>
</ul>

<h3>Recording Participant Consent</h3>
<ul>
    <li>If recording is enabled, notify participants beforehand</li>
    <li>Some jurisdictions require explicit consent before recording</li>
    <li>Include recording information in meeting invitations</li>
</ul>

<h3>Breakout Rooms</h3>
<p>For large meetings, divide participants into smaller groups:</p>
<ol>
    <li>Click "Breakout Rooms" in meeting controls</li>
    <li>Specify number of rooms and auto-assign participants</li>
    <li>Or manually assign specific people to each room</li>
    <li>Participants can work in their groups separately</li>
    <li>You can move participants between rooms as needed</li>
</ol>

<h2>Best Practices for Managing Participants</h2>

<h3>Before the Meeting</h3>
<ul>
    <li>Send calendar invitations 24-48 hours in advance</li>
    <li>Include meeting agenda and any preparation notes</li>
    <li>Specify any tech requirements (camera, microphone needed)</li>
    <li>Add a backup contact if they need to reach you</li>
</ul>

<h3>During the Meeting</h3>
<ul>
    <li>Start on time, even if not everyone has joined</li>
    <li>Greet participants as they join</li>
    <li>Mute participants with background noise</li>
    <li>Keep everyone engaged by asking questions</li>
    <li>Watch for hand raises or non-verbal cues</li>
</ul>

<h3>Communication</h3>
<ul>
    <li>Always ask permission before muting someone</li>
    <li>Be respectful when managing the meeting</li>
    <li>Thank people for joining and their time</li>
    <li>Share next steps and action items before closing</li>
</ul>

<h2>Troubleshooting Participant Issues</h2>

<h3>Participant Can't Join</h3>
<ul>
    <li>Verify they received the invitation email</li>
    <li>Check that the meeting has started</li>
    <li>Have them try a different browser</li>
    <li>Send them the meeting link directly via chat or email</li>
</ul>

<h3>Audio or Video Issues with a Participant</h3>
<ul>
    <li>Ask them to check their microphone/camera in system settings</li>
    <li>Have them mute and unmute to reset audio</li>
    <li>Suggest they disable video if bandwidth is limited</li>
    <li>Ask them to restart their browser</li>
</ul>

<h3>Participant Was Accidentally Removed</h3>
<ul>
    <li>Send them the meeting link again</li>
    <li>They can rejoin immediately if the meeting is still active</li>
    <li>Their participation in the attendance report will show the disconnect/rejoin</li>
</ul>

<div class="guides-success-box">
    <strong>✅ You're All Set!</strong> With these participant management tools, you can run smooth, organized meetings with complete control over the experience.
</div>
