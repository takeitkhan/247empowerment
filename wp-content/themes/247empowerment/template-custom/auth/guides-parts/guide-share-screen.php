<h2>Screen Sharing Basics</h2>
<p>Screen sharing allows you to share your entire screen, a specific application window, or a browser tab with meeting participants. It's perfect for presentations, demos, and collaborative work.</p>

<div class="guides-info-box">
    <strong>💡 Tip:</strong> Browser-based screen sharing works best when all participants are using the same video conferencing platform.
</div>

<h2>How to Share Your Screen</h2>

<!-- Step 1 -->
<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Join the Meeting</h4>
        <p>Make sure you're already in an active meeting. Only participants who have joined can share their screen.</p>
    </div>
</div>

<!-- Step 2 -->
<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Locate the Share Screen Button</h4>
        <p>Look for the "Share Screen" or "Screen Share" button in the meeting toolbar at the bottom or right side of your video window.</p>
    </div>
</div>

<!-- Step 3 -->
<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Choose What to Share</h4>
        <p>A dialog will appear with options:</p>
        <ul>
            <li><strong>Entire Screen:</strong> Share your complete desktop</li>
            <li><strong>Application Window:</strong> Share only a specific app (Chrome, Slack, Figma, etc.)</li>
            <li><strong>Browser Tab:</strong> Share only the current browser tab</li>
        </ul>
    </div>
</div>

<!-- Step 4 -->
<div class="guides-step">
    <div class="guides-step-number">4</div>
    <div class="guides-step-content">
        <h4>Select and Confirm</h4>
        <p>Click on what you want to share, then click "Share" or "Start Sharing" to begin.</p>
    </div>
</div>

<div class="guides-success-box">
    <strong>✅ Sharing Active!</strong> Your screen is now visible to all participants. Look for a red border or indicator showing you're sharing.
</div>

<h2>During Screen Sharing</h2>

<h3>Control Options</h3>
<ul>
    <li><strong>Pause Sharing:</strong> Temporarily hide your screen without ending the share</li>
    <li><strong>Switch Screen/App:</strong> Change what you're sharing without starting over</li>
    <li><strong>Stop Sharing:</strong> End screen sharing completely</li>
</ul>

<h3>Participant Controls</h3>
<ul>
    <li>Organizers can pause or stop screen sharing from any participant</li>
    <li>Participants can request to take control of the screen (if organizer allows)</li>
    <li>Disable "Allow Others to Control Screen" for security</li>
</ul>

<h3>Privacy Reminders</h3>
<ul>
    <li>Close sensitive applications before sharing your entire screen</li>
    <li>Be mindful of confidential information, passwords, or private data</li>
    <li>Hide notifications that might appear during sharing</li>
    <li>Use "Application Window" sharing instead of full screen to limit what's visible</li>
</ul>

<h2>Collaborative Annotation & Markup</h2>

<h3>Highlighting During Screen Share</h3>
<p>While sharing your screen, you can use annotation tools to highlight or draw attention to specific elements:</p>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Click the Drawing Tools Button</h4>
        <p>Look for a "Draw" or "Annotate" button in the screen share toolbar.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Select Your Tool</h4>
        <p>Choose from options like:</p>
        <ul>
            <li>Pen tool for drawing</li>
            <li>Highlighter tool</li>
            <li>Shape tools (arrows, rectangles, circles)</li>
            <li>Eraser tool</li>
            <li>Color picker</li>
        </ul>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Draw on Your Screen</h4>
        <p>Click and drag to draw on the shared screen. All participants will see your annotations in real-time.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">4</div>
    <div class="guides-step-content">
        <h4>Clear Annotations</h4>
        <p>Click "Clear All" to remove all annotations or "Undo" to remove the last one.</p>
    </div>
</div>

<h3>Allowing Participants to Draw</h3>
<p>You can allow other participants to annotate your shared screen:</p>
<ol>
    <li>Click the settings/options icon while sharing</li>
    <li>Enable "Allow participants to draw"</li>
    <li>They can now use annotation tools on your shared screen</li>
</ol>

<h2>Collaborative Editing</h2>

<h3>Remote Control of Your Screen</h3>
<p>Allow a trusted participant to control your screen while you collaborate:</p>
<ol>
    <li>While sharing, enable "Allow Remote Control"</li>
    <li>A participant can request control</li>
    <li>You'll see a prompt to approve or deny their request</li>
    <li>Once approved, they can use your mouse and keyboard</li>
    <li>You can revoke control at any time</li>
</ol>

<div class="guides-warning-box">
    <strong>⚠️ Security Note:</strong> Only enable remote control with trusted participants. Revoking control happens immediately when you press Escape or click the revoke button.
</div>

<h3>Collaborative Document Editing</h3>
<p>For real-time document collaboration:</p>
<ul>
    <li>Share a Google Docs/Sheets link so participants can edit simultaneously</li>
    <li>Share a Figma design board for design collaboration</li>
    <li>Share a GitHub repository for code reviews</li>
    <li>Use an online whiteboard tool for brainstorming</li>
</ul>

<h2>Advanced Sharing Scenarios</h2>

<h3>Presenting a Slideshow</h3>
<ul>
    <li>Open your presentation (PowerPoint, Google Slides, Keynote)</li>
    <li>Share the application window or browser tab</li>
    <li>Enter presentation/slideshow mode</li>
    <li>Only your slides will be visible to participants</li>
</ul>

<h3>Code Review & Pair Programming</h3>
<ul>
    <li>Share your IDE or code editor window</li>
    <li>Consider enabling remote control for pair programming</li>
    <li>Use chat to discuss specific code sections</li>
    <li>Reference line numbers when commenting on code</li>
</ul>

<h3>Product Demonstration</h3>
<ul>
    <li>Open the application you want to demo</li>
    <li>Share the application window (not entire screen)</li>
    <li>Walk participants through features step-by-step</li>
    <li>Take time to explain and answer questions</li>
</ul>

<h3>Workshop or Training Session</h3>
<ul>
    <li>Combine screen sharing with verbal instructions</li>
    <li>Use chat for Q&A and participant questions</li>
    <li>Record the session for participants to review later</li>
    <li>Provide handouts or resources after the session</li>
</ul>

<h2>Best Practices for Screen Sharing</h2>

<h3>Before You Share</h3>
<ul>
    <li>Close unnecessary browser tabs and applications</li>
    <li>Disable notifications to avoid interruptions</li>
    <li>Increase text size on your screen (easier to read from distance)</li>
    <li>Use a high-resolution monitor if possible</li>
    <li>Test your screen share with one person first</li>
</ul>

<h3>While Sharing</h3>
<ul>
    <li>Move your mouse slowly and deliberately</li>
    <li>Pause frequently to let people absorb information</li>
    <li>Narrate what you're doing clearly</li>
    <li>Don't minimize the shared window accidentally</li>
    <li>Watch for non-verbal cues (questions, confusion) in participant faces</li>
</ul>

<h3>Technical Tips</h3>
<ul>
    <li>For very large files, use application window sharing instead of full screen</li>
    <li>If screen sharing stutters, reduce the resolution or close background apps</li>
    <li>Use a wired internet connection for smoother sharing</li>
    <li>Close VPN if it's causing latency issues</li>
</ul>

<h2>Troubleshooting Screen Share Issues</h2>

<h3>Screen Share Button Not Available</h3>
<ul>
    <li>Ensure you've joined the meeting (not just opening the link)</li>
    <li>Check that screen sharing is enabled for this meeting</li>
    <li>Try refreshing your browser</li>
    <li>Make sure you're using a supported browser</li>
</ul>

<h3>Screen Share is Laggy or Freezing</h3>
<ul>
    <li>Reduce video quality in meeting settings</li>
    <li>Close applications running in the background</li>
    <li>Use a wired Ethernet connection</li>
    <li>Reduce the number of participants with video enabled</li>
    <li>Try sharing a specific application instead of your entire screen</li>
</ul>

<h3>Participants Can't See Your Screen</h3>
<ul>
    <li>Check that screen sharing is actually active (look for red border)</li>
    <li>Ask a participant to refresh their browser</li>
    <li>Try stopping and restarting the screen share</li>
    <li>Verify your internet connection is stable</li>
    <li>Switch to sharing a different application</li>
</ul>

<h3>Remote Control Not Working</h3>
<ul>
    <li>Ensure "Allow Remote Control" is explicitly enabled</li>
    <li>Check that the participant has requested control and you approved it</li>
    <li>Try disabling and re-enabling remote control</li>
    <li>Ask the participant to try again</li>
</ul>

