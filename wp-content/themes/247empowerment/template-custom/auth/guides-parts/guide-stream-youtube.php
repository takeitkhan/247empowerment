<div class="guides-info-box">
    <strong>💡 Tip:</strong> YouTube keeps your stream archive for up to 12 hours for testing. Save important streams to your channel permanently.
</div>

<h2>Troubleshooting Streaming Issues</h2>

<h3>Stream Won't Start</h3>
<ul>
    <li>Verify YouTube channel has live streaming enabled (24-48 hour wait for new channels)</li>
    <li>Check internet connection speed (need at least 2.5 Mbps upload)</li>
    <li>Try disconnecting and reconnecting YouTube account</li>
    <li>Refresh the browser and try again</li>
</ul>

<h3>Poor Stream Quality</h3>
<ul>
    <li>Reduce video resolution in meeting settings</li>
    <li>Close other applications using bandwidth</li>
    <li>Move closer to your router or use wired connection</li>
    <li>Ask participants to disable video if not presenting</li>
</ul>

<h3>Stream Keeps Disconnecting</h3>
<ul>
    <li>Restart your internet connection</li>
    <li>Check for network interference (WiFi channel congestion)</li>
    <li>Use an Ethernet cable for more stable connection</li>
    <li>Reduce number of active participants if very high</li>
</ul>

<h3>Stream Not Appearing on YouTube</h3>
<ul>
    <li>Check that live streaming is enabled on your YouTube channel</li>
    <li>Verify you clicked "Start Streaming" in the meeting</li>
    <li>Allow a few seconds for the stream to appear on YouTube</li>
    <li>Check YouTube's live dashboard directly for the stream</li>
</ul>

<div class="guides-warning-box">
    <strong>⚠️ Important:</strong> Always test your stream setup with a private or unlisted stream first before going public to ensure everything works properly.
</div>
