<h2>Live Streaming to YouTube</h2>
<p>Stream your meetings directly to YouTube to reach a wider audience. This guide walks you through setting up and managing your live stream.</p>

<div class="guides-info-box">
    <strong>💡 Tip:</strong> You'll need a YouTube channel to stream. You can create one for free if you don't have one already.
</div>

<h2>Before You Start</h2>

<div class="guides-warning-box">
    <strong>⚠️ Requirements:</strong>
    <ul>
        <li>A YouTube channel (free or paid)</li>
        <li>Enabled Live Streaming feature on your YouTube channel (may take 24 hours)</li>
        <li>Admin or organizer role in the meeting</li>
        <li>Stable internet connection (at least 2.5 Mbps upload speed)</li>
    </ul>
</div>

<h3>Enable Live Streaming on YouTube</h3>
<ol>
    <li>Go to <strong>youtube.com</strong> and sign into your account</li>
    <li>Click your profile icon and select <strong>"Create a channel"</strong> if you don't have one</li>
    <li>Go to <strong>Studio</strong> (top menu)</li>
    <li>Select <strong>"Create"</strong> → <strong>"Go live"</strong></li>
    <li>Follow the setup process to enable live streaming</li>
    <li><strong>Note:</strong> YouTube may require 24-48 hours to enable this feature for new channels</li>
</ol>

<h2>Connect Your YouTube Account</h2>

<!-- Step 1 -->
<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Open Meeting Settings</h4>
        <p>While creating or editing a meeting, scroll to the "Streaming" section.</p>
    </div>
</div>

<!-- Step 2 -->
<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Click "Connect YouTube Account"</h4>
        <p>Select YouTube as your streaming platform and click the connect button.</p>
    </div>
</div>

<!-- Step 3 -->
<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Authorize Access</h4>
        <p>You'll be redirected to YouTube to authorize the platform. Sign in with your YouTube account and grant permission to stream.</p>
    </div>
</div>

<!-- Step 4 -->
<div class="guides-step">
    <div class="guides-step-number">4</div>
    <div class="guides-step-content">
        <h4>Select Your Channel</h4>
        <p>If you manage multiple YouTube channels, select the one where you want to stream.</p>
    </div>
</div>

<h2>Configure Stream Settings</h2>

<!-- Step 5 -->
<div class="guides-step">
    <div class="guides-step-number">5</div>
    <div class="guides-step-content">
        <h4>Set Stream Title & Description</h4>
        <p>Enter a descriptive title for your stream (e.g., "Q1 Marketing Strategy Discussion"). Add a description to help viewers understand the content.</p>
    </div>
</div>

<!-- Step 6 -->
<div class="guides-step">
    <div class="guides-step-number">6</div>
    <div class="guides-step-content">
        <h4>Choose Stream Visibility</h4>
        <p>Select how the stream appears on YouTube:</p>
        <ul>
            <li><strong>Public:</strong> Anyone can find and watch</li>
            <li><strong>Unlisted:</strong> Only people with the link can watch</li>
            <li><strong>Private:</strong> Only people you invite can watch</li>
        </ul>
    </div>
</div>

<!-- Step 7 -->
<div class="guides-step">
    <div class="guides-step-number">7</div>
    <div class="guides-step-content">
        <h4>Add Thumbnail & Tags (Optional)</h4>
        <p>Upload a custom thumbnail and add relevant tags to help viewers discover your stream.</p>
    </div>
</div>

<h2>Start Streaming</h2>

<!-- Step 8 -->
<div class="guides-step">
    <div class="guides-step-number">8</div>
    <div class="guides-step-content">
        <h4>Begin Your Meeting</h4>
        <p>Start the meeting as usual by clicking "Join Room" or having participants join through invitations.</p>
    </div>
</div>

<!-- Step 9 -->
<div class="guides-step">
    <div class="guides-step-number">9</div>
    <div class="guides-step-content">
        <h4>Enable Streaming</h4>
        <p>Once everyone is in the meeting, click the "Go Live" or "Start Streaming" button in the meeting toolbar.</p>
    </div>
</div>

<!-- Step 10 -->
<div class="guides-step">
    <div class="guides-step-number">10</div>
    <div class="guides-step-content">
        <h4>Share Stream Link</h4>
        <p>A YouTube stream link will be generated. You can share this with people who want to watch the live stream.</p>
    </div>
</div>

<div class="guides-success-box">
    <strong>🔴 LIVE!</strong> Your stream is now live on YouTube. The red indicator shows your stream is active.
</div>

<h2>During Your Stream</h2>

<h3>Monitoring Your Stream Quality</h3>
<ul>
    <li>Check the stream health indicator in the meeting control panel</li>
    <li>Look for any warnings about bitrate or connection issues</li>
    <li>Monitor YouTube's live dashboard in a separate tab if needed</li>
</ul>

<h3>Interacting with Viewers</h3>
<ul>
    <li>YouTube chat is separate from your meeting chat</li>
    <li>Viewers can comment on YouTube; this doesn't appear in your meeting</li>
    <li>You can see viewer count in real-time on YouTube's dashboard</li>
    <li>Read YouTube chat by opening the YouTube live dashboard</li>
</ul>

<h3>Best Practices During Stream</h3>
<ul>
    <li>Ensure good lighting and a professional background</li>
    <li>Speak clearly and maintain a steady pace</li>
    <li>Let viewers know they can ask questions in the chat</li>
    <li>Take breaks every 30-45 minutes for longer streams</li>
    <li>Have a co-host monitor YouTube chat while you present</li>
</ul>

<h2>End Streaming</h2>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Stop the Stream</h4>
        <p>Click the "Stop Streaming" button in the meeting toolbar when you're ready to end the stream.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Confirm Ending</h4>
