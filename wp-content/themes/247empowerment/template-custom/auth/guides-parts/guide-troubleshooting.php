<h2>Common Issues & Solutions</h2>
<p>This troubleshooting guide covers the most frequently encountered issues and how to resolve them quickly.</p>

<div class="guides-info-box">
    <strong>💡 Tip:</strong> Before troubleshooting, try the "classic" fixes: restart your browser, check your internet connection, and ensure you're using an updated browser version.
</div>

<h2>Audio & Microphone Issues</h2>

<h3>Microphone Not Working</h3>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Check Browser Permissions</h4>
        <p>The browser needs permission to access your microphone:</p>
        <ul>
            <li><strong>Chrome/Edge:</strong> Look for a camera/microphone icon in the address bar</li>
            <li><strong>Firefox:</strong> Check the address bar for a permissions icon</li>
            <li><strong>Safari:</strong> Go to System Preferences → Security & Privacy → Microphone</li>
        </ul>
        <p>Click the icon and ensure microphone access is allowed.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Select Correct Microphone</h4>
        <p>In the meeting settings:</p>
        <ol>
            <li>Look for audio settings (usually a gear icon)</li>
            <li>Check the "Microphone" dropdown</li>
            <li>Select your physical microphone (e.g., "Built-in Microphone")</li>
            <li>Test by speaking into the microphone</li>
        </ol>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Check System Settings</h4>
        <p>Verify your device recognizes the microphone:</p>
        <ul>
            <li><strong>Windows:</strong> Settings → Sound → Recording devices</li>
            <li><strong>Mac:</strong> System Preferences → Sound → Input</li>
            <li><strong>iPhone/iPad:</strong> Settings → Privacy → Microphone</li>
            <li><strong>Android:</strong> Settings → Apps → Permissions → Microphone</li>
        </ul>
        <p>Make sure your microphone is selected and not muted.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">4</div>
    <div class="guides-step-content">
        <h4>Test Your Microphone</h4>
        <p>Before joining a meeting:</p>
        <ol>
            <li>Use Windows Voice Recorder or Mac Voice Memos to test</li>
            <li>Try unplugging and re-plugging USB headphones</li>
            <li>Restart your browser and test again</li>
            <li>Try a different browser if available</li>
        </ol>
    </div>
</div>

<h3>Echo or Feedback Loop</h3>
<ul>
    <li><strong>Use Headphones:</strong> The most common cause - switch from speakers to headphones</li>
    <li><strong>Move Away from Speakers:</strong> Increase distance between your microphone and speakers</li>
    <li><strong>Lower Volume:</strong> Reduce speaker volume while in the meeting</li>
    <li><strong>Mute Others:</strong> Ask other participants with noise to mute</li>
    <li><strong>Disable "Acoustic Echo Cancellation":</strong> Try toggling this in advanced audio settings</li>
</ul>

<h3>Others Can't Hear Me</h3>
<ul>
    <li>Check that you're unmuted (look for microphone icon in meeting)</li>
    <li>Verify your browser has permission to use the microphone</li>
    <li>Check microphone levels in system settings (not at 0%)</li>
    <li>Try speaking closer to the microphone</li>
    <li>Restart the meeting if the audio didn't initialize properly</li>
</ul>

<h2>Video & Camera Issues</h2>

<h3>Camera Not Working</h3>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Check Browser Permissions</h4>
        <p>Click the camera icon in your browser's address bar and allow camera access for this website.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Select Correct Camera</h4>
        <p>If you have multiple cameras (external + built-in):</p>
        <ol>
            <li>Go to meeting settings (gear icon)</li>
            <li>Look for "Camera" dropdown</li>
            <li>Select your desired camera</li>
            <li>Check if video preview appears</li>
        </ol>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Check System Privacy Settings</h4>
        <p>Your operating system must allow camera access:</p>
        <ul>
            <li><strong>Windows:</strong> Settings → Privacy → Camera</li>
            <li><strong>Mac:</strong> System Preferences → Security & Privacy → Camera</li>
            <li><strong>iOS:</strong> Settings → Privacy → Camera</li>
            <li><strong>Android:</strong> Settings → Apps → Permissions → Camera</li>
        </ul>
        <p>Add your browser to the allowed apps list.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">4</div>
    <div class="guides-step-content">
        <h4>Test Your Camera</h4>
        <p>Use your system's built-in camera app to verify it works:</p>
        <ul>
            <li><strong>Windows:</strong> Camera app</li>
            <li><strong>Mac:</strong> Photo Booth</li>
            <li><strong>iPhone:</strong> Camera app</li>
            <li><strong>Android:</strong> Camera app</li>
        </ul>
    </div>
</div>

<h3>Camera Shows Black Screen</h3>
<ul>
    <li>Check if physical camera lens is clean</li>
    <li>Make sure nothing is covering the camera</li>
    <li>Check if another app is using the camera (close it)</li>
    <li>Refresh the browser and try again</li>
    <li>Restart your device</li>
</ul>

<h3>Video is Choppy or Pixelated</h3>
<ul>
    <li><strong>Lower Video Quality:</strong> Go to settings and reduce resolution</li>
    <li><strong>Close Background Apps:</strong> Free up computer resources</li>
    <li><strong>Improve Internet:</strong> Move closer to router or use wired connection</li>
    <li><strong>Better Lighting:</strong> Brighter rooms = sharper video</li>
    <li><strong>Disable Other Video:</strong> Ask others to turn off video if bandwidth limited</li>
</ul>

<h2>Connection & Network Issues</h2>

<h3>Slow or Laggy Meeting Experience</h3>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Check Your Internet Speed</h4>
        <p>Visit <strong>speedtest.net</strong> to check your connection:</p>
        <ul>
            <li><strong>Required:</strong> At least 2.5 Mbps download, 2.5 Mbps upload</li>
            <li><strong>Recommended:</strong> 5 Mbps+ download, 5 Mbps+ upload</li>
            <li>If below requirements, you may experience lag</li>
        </ul>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Close Bandwidth Hogs</h4>
        <p>Other apps using internet will slow down your meeting:</p>
        <ul>
            <li>Close file-sharing apps (OneDrive, Google Drive)</li>
            <li>Stop downloads or streaming services</li>
            <li>Close unnecessary browser tabs</li>
            <li>Pause cloud syncs temporarily</li>
        </ul>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Improve Your Connection</h4>
        <p>Physical connection is more stable than wireless:</p>
        <ul>
            <li>Use Ethernet cable if possible (directly to router)</li>
            <li>Move closer to WiFi router</li>
            <li>Restart your router (unplug 10 seconds, plug back in)</li>
            <li>Switch to 5GHz WiFi if available</li>
            <li>Use mobile hotspot as backup if WiFi is slow</li>
        </ul>
    </div>
</div>

<h3>Can't Connect to Meeting</h3>
<ul>
    <li>Check internet connection (try opening a website)</li>
    <li>Check if meeting has started (organizer may not have joined yet)</li>
    <li>Verify meeting link is correct</li>
    <li>Try a different browser</li>
    <li>Clear browser cache: Settings → Clear Browsing Data</li>
    <li>Disable VPN (if using one) and try again</li>
</ul>

<h3>Keep Getting Disconnected</h3>
<ul>
    <li>Check Wi-Fi signal strength (should show 3-4 bars)</li>
    <li>Move to a location with better signal</li>
    <li>Restart router and reconnect</li>
    <li>Switch from WiFi to wired Ethernet</li>
    <li>Close other devices using the same WiFi</li>
    <li>Contact your internet service provider if problem persists</li>
</ul>

<h2>Browser & Compatibility Issues</h2>

<h3>Browser Not Supported</h3>
<p>Make sure you're using a compatible browser:</p>
<ul>
    <li>✅ <strong>Supported:</strong> Chrome, Edge, Firefox, Safari (latest versions)</li>
    <li>❌ <strong>Not Supported:</strong> Internet Explorer, Opera, older versions</li>
</ul>

<p><strong>Solution:</strong> Download and use one of the supported browsers</p>

<h3>Update Your Browser</h3>
<p>Outdated browsers often have compatibility issues:</p>
<ul>
    <li><strong>Chrome:</strong> Menu → Settings → About Chrome (auto-updates)</li>
    <li><strong>Firefox:</strong> Menu → Help → About Firefox (auto-updates)</li>
    <li><strong>Safari:</strong> App Store → Updates tab</li>
    <li><strong>Edge:</strong> Menu → Settings → About Microsoft Edge (auto-updates)</li>
</ul>

<h3>Extensions Causing Problems</h3>
<p>Browser extensions can interfere with video meetings:</p>
<ol>
    <li>Try disabling all extensions (Chrome: Settings → Extensions)</li>
    <li>If meeting works, re-enable extensions one at a time</li>
    <li>Disable the problematic extension</li>
    <li>Common culprits: ad blockers, password managers, privacy tools</li>
</ol>

<h2>Account & Login Issues</h2>

<h3>Can't Log In</h3>
<ul>
    <li>Verify your email address is correct</li>
    <li>Check Caps Lock and password carefully</li>
    <li>Use "Forgot Password" to reset if needed</li>
    <li>Check spam folder for password reset email</li>
    <li>Try a different browser</li>
    <li>Clear browser cache and try again</li>
</ul>

<h3>Account Locked</h3>
<ul>
    <li>Too many failed login attempts trigger security lock</li>
    <li>Wait 30 minutes before trying again</li>
    <li>Or use "Forgot Password" to verify your email and unlock</li>
    <li>Contact support if still unable to access</li>
</ul>

<h2>Meeting Feature Issues</h2>

<h3>Screen Share Not Available</h3>
<ul>
    <li>Verify you're inside the meeting (not just at the link)</li>
    <li>Check if screen sharing is enabled for this meeting</li>
    <li>Check if you have permission (organizer only vs all participants)</li>
    <li>Try refreshing your browser page</li>
    <li>Restart the browser entirely</li>
</ul>

<h3>Recording Not Working</h3>
<ul>
    <li>Verify recording is enabled in meeting settings</li>
    <li>Check you have permission to record (organizer only)</li>
    <li>Ensure sufficient storage space on device</li>
    <li>Verify browser hasn't blocked microphone/camera (which stops recording)</li>
    <li>Try starting/stopping recording again</li>
</ul>

<h3>Chat Not Visible or Working</h3>
<ul>
    <li>Click "Chat" button in meeting toolbar to open chat panel</li>
    <li>Check if chat is disabled by organizer</li>
    <li>Refresh browser if chat appears frozen</li>
    <li>Try a different browser if persistent</li>
</ul>

<h2>Mobile Device Issues</h2>

<h3>Meeting on Phone/Tablet</h3>
<ul>
    <li>Use the web browser, not just the app (for better compatibility)</li>
    <li>Grant microphone/camera permissions when prompted</li>
    <li>Ensure good WiFi or cellular signal</li>
    <li>Close other apps to free up memory</li>
    <li>Keep device upright for better video angle</li>
</ul>

<h3>App Won't Install or Update</h3>
<ul>
    <li>Check available storage space on device</li>
    <li>Update iOS or Android to latest version</li>
    <li>Try uninstalling and reinstalling the app</li>
    <li>Restart the device</li>
    <li>Use web browser version as alternative</li>
</ul>

