<h2 id="manage-attendees">👥 Managing Attendees & Participants</h2>

<p>As a meeting organizer, you have full control over who participates in your meetings and what they can do.</p>

<div class="guides-info-box">
    <strong>💡 Tip:</strong> Only meeting organizers and co-hosts can manage participants. Regular attendees can see the participant list but cannot remove others.
</div>

<h3>Before the Meeting: Inviting Participants</h3>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Open the Participants Section</h4>
        <p>When creating a new meeting, find the "Add Participants" or "Invitees" section in the form.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Enter Email Addresses</h4>
        <p>Type or paste email addresses of people you want to invite. You can add multiple addresses separated by commas.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Set Participant Roles</h4>
        <p>Choose role for each participant:</p>
        <ul>
            <li><strong>Co-Host:</strong> Can manage other participants, mute/unmute, etc.</li>
            <li><strong>Presenter:</strong> Can share screen and present</li>
            <li><strong>Attendee:</strong> Can join and view but not present</li>
        </ul>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">4</div>
    <div class="guides-step-content">
        <h4>Send Invitations</h4>
        <p>When you save the meeting, invitations are automatically sent to all participants with the meeting link and details.</p>
    </div>
</div>

<h3>During the Meeting: Managing Participants</h3>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Click the Participants Button</h4>
        <p>Look for the "Participants" icon in the meeting toolbar (usually shows as a people icon).</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>View the List</h4>
        <p>A panel will open showing everyone currently in the meeting, plus their status (camera on/off, muted/unmuted).</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Access Participant Options</h4>
        <p>Hover over or right-click a participant's name to see available actions (if you're the organizer).</p>
    </div>
</div>

<h3>Participant Management Actions</h3>

<h4>Mute/Unmute Participants</h4>
<ul>
    <li><strong>Mute Individual:</strong> Click the microphone icon next to a participant to mute their audio</li>
    <li><strong>Mute All:</strong> Use "Mute All" button to silence everyone except yourself</li>
    <li><strong>Unmute:</strong> Click again to allow them to speak</li>
</ul>

<h4>Control Participant Video</h4>
<ul>
    <li><strong>Stop Participant Video:</strong> Click the camera icon to turn off someone's video</li>
    <li><strong>Require Video:</strong> Some organizers require video to be on for active participation</li>
</ul>

<h4>Spotlight a Participant</h4>
<p>Make one participant's video prominent for everyone to see:</p>
<ol>
    <li>Find the participant in the list</li>
    <li>Look for "Spotlight" or "Make Host Video" option</li>
    <li>Click it to make their video the main view</li>
</ol>

<h4>Remove a Participant</h4>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Find the Participant</h4>
        <p>Locate the person you want to remove in the participant list.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Right-Click or Hover</h4>
        <p>Right-click their name or hover over it to reveal the menu options.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Click "Remove" or "Remove Participant"</h4>
        <p>Select the remove option. They will be disconnected from the meeting immediately.</p>
    </div>
</div>

<div class="guides-warning-box">
    <strong>⚠️ Note:</strong> Removed participants can rejoin using the original meeting link (unless you disable this).
</div>

<h3>After the Meeting: Attendance Reports</h3>

<ol>
    <li>Go to "Upcoming Meetings & Events" after the meeting ends</li>
    <li>Find the meeting in your list</li>
    <li>Click "View Details" or "Attendance Report"</li>
    <li>See a list of who joined and for how long</li>
    <li>Export the report as CSV or PDF</li>
</ol>

<div class="guides-success-box">
    <strong>✅ You're All Set!</strong> With these participant management tools, you can run smooth, organized meetings with complete control.
</div>

<!-- TROUBLESHOOTING -->
<h2 id="troubleshooting">🔧 Troubleshooting & Support</h2>

<p>This troubleshooting guide covers the most frequently encountered issues and how to resolve them quickly.</p>

<div class="guides-info-box">
    <strong>💡 Tip:</strong> Before troubleshooting, try the "classic" fixes: restart your browser, check your internet connection, and ensure you're using an updated browser version.
</div>

<h3>Audio & Microphone Issues</h3>

<h4>Microphone Not Working</h4>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Check Browser Permissions</h4>
        <p>The browser needs permission to access your microphone:</p>
        <ul>
            <li><strong>Chrome/Edge:</strong> Look for a camera/microphone icon in the address bar</li>
            <li><strong>Firefox:</strong> Check the address bar for a permissions icon</li>
            <li><strong>Safari:</strong> Go to System Preferences → Security & Privacy → Microphone</li>
        </ul>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Select Correct Microphone</h4>
        <p>In the meeting settings, look for "Microphone" dropdown and select your physical microphone.</p>
    </div>
</div>

<h4>Echo or Feedback Loop</h4>
<ul>
    <li><strong>Use Headphones:</strong> The most common cause - switch from speakers to headphones</li>
    <li><strong>Move Away from Speakers:</strong> Increase distance between microphone and speakers</li>
    <li><strong>Lower Volume:</strong> Reduce speaker volume while in the meeting</li>
</ul>

<h3>Video & Camera Issues</h3>

<h4>Camera Not Working</h4>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Check Browser Permissions</h4>
        <p>Click the camera icon in your browser's address bar and allow camera access for this website.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Select Correct Camera</h4>
        <p>If you have multiple cameras, go to meeting settings and select your desired camera from the dropdown.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Check System Privacy Settings</h4>
        <p><strong>Windows:</strong> Settings → Privacy → Camera | <strong>Mac:</strong> System Preferences → Security & Privacy → Camera</p>
    </div>
</div>

<h4>Video is Choppy or Pixelated</h4>
<ul>
    <li><strong>Lower Video Quality:</strong> Go to settings and reduce resolution</li>
    <li><strong>Close Background Apps:</strong> Free up computer resources</li>
    <li><strong>Improve Internet:</strong> Move closer to router or use wired connection</li>
    <li><strong>Better Lighting:</strong> Brighter rooms = sharper video</li>
</ul>

<h3>Connection & Network Issues</h3>

<h4>Slow or Laggy Meeting Experience</h4>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Check Your Internet Speed</h4>
        <p>Visit <strong>speedtest.net</strong> to check your connection:</p>
        <ul>
            <li><strong>Required:</strong> At least 2.5 Mbps download, 2.5 Mbps upload</li>
            <li><strong>Recommended:</strong> 5 Mbps+ download, 5 Mbps+ upload</li>
        </ul>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Close Bandwidth Hogs</h4>
        <p>Close file-sharing apps, stop downloads, close unnecessary browser tabs, pause cloud syncs.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Improve Your Connection</h4>
        <p>Use Ethernet cable if possible, move closer to router, restart your router, or switch to 5GHz WiFi.</p>
    </div>
</div>

<h4>Keep Getting Disconnected</h4>
<ul>
    <li>Check Wi-Fi signal strength (should show 3-4 bars)</li>
    <li>Move to a location with better signal</li>
    <li>Restart router and reconnect</li>
    <li>Switch from WiFi to wired Ethernet</li>
    <li>Close other devices using the same WiFi</li>
</ul>

<h3>Browser & Compatibility Issues</h3>

<h4>Browser Not Supported</h4>
<p>Make sure you're using a compatible browser:</p>
<ul>
    <li>✅ <strong>Supported:</strong> Chrome, Edge, Firefox, Safari (latest versions)</li>
    <li>❌ <strong>Not Supported:</strong> Internet Explorer, Opera, older versions</li>
</ul>

<h4>Update Your Browser</h4>
<ul>
    <li><strong>Chrome:</strong> Menu → Settings → About Chrome (auto-updates)</li>
    <li><strong>Firefox:</strong> Menu → Help → About Firefox (auto-updates)</li>
    <li><strong>Safari:</strong> App Store → Updates tab</li>
</ul>

<h4>Extensions Causing Problems</h4>
<p>Try disabling all browser extensions. If meeting works, re-enable them one at a time to find the culprit. Common culprits: ad blockers, password managers, privacy tools.</p>

<h3>Quick Troubleshooting Checklist</h3>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Restart Your Browser</h4>
        <p>Close completely and reopen (not just refresh)</p>
    </div>
</div>

