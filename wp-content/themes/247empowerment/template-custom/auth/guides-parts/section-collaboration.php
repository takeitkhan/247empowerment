<!-- CREATE A MEETING -->
<h2 id="create-meeting">➕ How to Create a Meeting</h2>

<p>Creating a meeting is simple and takes just a few minutes. Follow these steps to set up your first meeting.</p>

<div class="guides-info-box">
    <strong>💡 Tip:</strong> You can create meetings for one-on-one calls, team huddles, or large group presentations.
</div>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Navigate to Upcoming Meetings</h4>
        <p>From the Collaboration Hub, click on "📅 Upcoming Meetings & Events" in the left sidebar to access the meetings dashboard.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Click "Create New Meeting" Button</h4>
        <p>Look for the prominent "➕ Create New Meeting" button at the top of the meetings list. Click it to open the meeting creation form.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Fill in Meeting Details</h4>
        <p>Enter the following information:</p>
        <ul>
            <li><strong>Meeting Title:</strong> Give your meeting a descriptive name (e.g., "Q1 Planning Session")</li>
            <li><strong>Description:</strong> Add optional details about the meeting agenda</li>
            <li><strong>Date & Time:</strong> Select when you want the meeting to take place</li>
            <li><strong>Duration:</strong> Specify how long the meeting should last</li>
            <li><strong>Participants:</strong> Add email addresses of people you want to invite</li>
        </ul>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">4</div>
    <div class="guides-step-content">
        <h4>Configure Meeting Settings (Optional)</h4>
        <p>Customize your meeting experience:</p>
        <ul>
            <li><strong>Recording:</strong> Enable to record the meeting automatically</li>
            <li><strong>Screen Sharing:</strong> Allow participants to share their screens</li>
            <li><strong>Chat:</strong> Enable in-meeting chat for participants</li>
            <li><strong>Waiting Room:</strong> Require approval for participants joining</li>
        </ul>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">5</div>
    <div class="guides-step-content">
        <h4>Save & Send Invitations</h4>
        <p>Click the "Create Meeting" button. Invitations will automatically be sent to all participants via email with a link to join.</p>
    </div>
</div>

<h3>Advanced Options</h3>

<h4>Setting a Meeting Password</h4>
<p>Protect your meeting with a password. Participants will need to enter this password when joining. This is useful for sensitive discussions.</p>

<h4>Recurring Meetings</h4>
<p>Set up recurring meetings that repeat daily, weekly, or monthly. Choose your recurrence pattern and end date. All participants will receive calendar invitations for each occurrence.</p>

<h4>Breakout Rooms</h4>
<p>For larger groups, you can create breakout rooms where participants are divided into smaller groups for focused discussions. You can move participants between rooms as needed.</p>

<div class="guides-success-box">
    <strong>✅ Great!</strong> Your meeting has been created. Participants will receive invitations and you'll be notified when they join.
</div>

<h3>Tips for Successful Meetings</h3>
<ul>
    <li>Send invitations at least 24 hours in advance when possible</li>
    <li>Use descriptive titles so participants know what to expect</li>
    <li>Test your audio and video 5 minutes before the meeting starts</li>
    <li>Have a clear agenda to keep the meeting focused</li>
    <li>Enable recording if you want to share highlights later</li>
</ul>

<div class="guides-warning-box">
    <strong>⚠️ Note:</strong> Free accounts can host up to 3 simultaneous meetings. Upgrade to host more meetings at once.
</div>

<!-- JOIN A MEETING -->
<h2 id="join-meeting">🚪 How to Join a Meeting</h2>

<p>Joining a meeting is straightforward. You can join from an email invitation, calendar link, or directly from the platform.</p>

<div class="guides-info-box">
    <strong>💡 Tip:</strong> Test your microphone and camera before joining to ensure they work properly.
</div>

<h3>Method 1: From Email Invitation</h3>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Check Your Email</h4>
        <p>Look for an email invitation from the meeting organizer with the subject line containing the meeting title.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Click the Join Link</h4>
        <p>Click the "Join Meeting" button or link in the email. This will open the platform and take you to the meeting waiting room.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Enter Your Details (if required)</h4>
        <p>If this is your first time, enter your name and email. If a password is required, enter it when prompted.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">4</div>
    <div class="guides-step-content">
        <h4>Enable Media & Join</h4>
        <p>Allow access to your camera and microphone when prompted. Then click "Join Room" to enter the video conference.</p>
    </div>
</div>

<h3>Method 2: From the Collaboration Hub</h3>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Go to Upcoming Meetings</h4>
        <p>Log into your account and navigate to "📅 Upcoming Meetings & Events" in the Collaboration Hub.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Find Your Meeting</h4>
        <p>Scroll through the list and find the meeting you want to join. It will show the title, time, and organizer.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Click "Join Room"</h4>
        <p>Click the "Join Room" button next to the meeting. You'll be taken to the video conference interface.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">4</div>
    <div class="guides-step-content">
        <h4>Enter the Meeting</h4>
        <p>When ready, click "Join Room" to enter the video conference with other participants.</p>
    </div>
</div>

<h3>In-Meeting Controls</h3>

<h4>Audio & Video Controls</h4>
<ul>
    <li><strong>Mute/Unmute:</strong> Toggle your microphone on and off</li>
    <li><strong>Camera On/Off:</strong> Toggle your video on and off</li>
    <li><strong>Speaker Selection:</strong> Choose which speakers to use (if multiple available)</li>
</ul>

<h4>Meeting Chat</h4>
<p>Send messages to other participants using the chat feature:</p>
<ol>
    <li>Click the "Chat" button in the meeting toolbar</li>
    <li>Type your message in the text box</li>
    <li>Press Enter or click "Send"</li>
</ol>

<h4>Participant List</h4>
<p>View who's in the meeting:</p>
<ol>
    <li>Click the "Participants" button</li>
    <li>See a list of everyone currently in the meeting</li>
    <li>Organizers can mute, spotlight, or remove participants from this list</li>
</ol>

<h3>Common Connection Issues</h3>

<div class="guides-warning-box">
    <strong>🔴 Connection Problems?</strong> Try these solutions:
</div>

<h4>Camera or Microphone Not Working</h4>
<ul>
    <li>Check browser permissions and allow access to camera/microphone</li>
    <li>Verify the correct camera/microphone is selected in settings</li>
    <li>Restart your browser and join again</li>
    <li>Test your devices using your computer's system settings</li>
</ul>

<h4>Audio Feedback or Echo</h4>
<ul>
    <li>Use headphones instead of speakers</li>
    <li>Move away from speakers or increase the distance</li>
    <li>Lower speaker volume while in the meeting</li>
    <li>Check microphone sensitivity in advanced settings</li>
</ul>

<h4>Choppy Video or Lag</h4>
<ul>
    <li>Close other applications using your internet connection</li>
    <li>Move closer to your router or use a wired connection</li>
    <li>Lower video quality in meeting settings</li>
    <li>Try disabling video to improve audio quality</li>
</ul>

<div class="guides-success-box">
    <strong>✅ You're In!</strong> Welcome to the meeting. Take a moment to check your audio and video are working properly before the meeting starts.
</div>

<!-- SCREEN SHARING -->
<h2 id="screen-sharing">🖥️ Screen Sharing & Collaboration</h2>

<p>Screen sharing allows you to share your entire screen, a specific application window, or a browser tab with meeting participants. It's perfect for presentations, demos, and collaborative work.</p>

<div class="guides-info-box">
    <strong>💡 Tip:</strong> Browser-based screen sharing works best when all participants are using the same video conferencing platform.
</div>

<h3>How to Share Your Screen</h3>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Join the Meeting</h4>
        <p>Make sure you're already in an active meeting. Only participants who have joined can share their screen.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Locate the Share Screen Button</h4>
        <p>Look for the "Share Screen" or "Screen Share" button in the meeting toolbar at the bottom or right side of your video window.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Choose What to Share</h4>
        <p>A dialog will appear with options:</p>
        <ul>
            <li><strong>Entire Screen:</strong> Share your complete desktop</li>
            <li><strong>Application Window:</strong> Share only a specific app (Chrome, Slack, Figma, etc.)</li>
            <li><strong>Browser Tab:</strong> Share only the current browser tab</li>
        </ul>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">4</div>
    <div class="guides-step-content">
        <h4>Select and Confirm</h4>
        <p>Click on what you want to share, then click "Share" or "Start Sharing" to begin.</p>
    </div>
</div>

<div class="guides-success-box">
    <strong>✅ Sharing Active!</strong> Your screen is now visible to all participants. Look for a red border or indicator showing you're sharing.
</div>

<h3>During Screen Sharing</h3>

<h4>Control Options</h4>
<ul>
    <li><strong>Pause Sharing:</strong> Temporarily hide your screen without ending the share</li>
    <li><strong>Switch Screen/App:</strong> Change what you're sharing without starting over</li>
    <li><strong>Stop Sharing:</strong> End screen sharing completely</li>
</ul>

<h4>Participant Controls</h4>
<ul>
    <li>Organizers can pause or stop screen sharing from any participant</li>
    <li>Participants can request to take control of the screen (if organizer allows)</li>
    <li>Disable "Allow Others to Control Screen" for security</li>
</ul>

<h3>Collaborative Annotation & Markup</h3>

<p>While sharing your screen, you can use annotation tools to highlight or draw attention to specific elements:</p>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Click the Drawing Tools Button</h4>
        <p>Look for a "Draw" or "Annotate" button in the screen share toolbar.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Select Your Tool</h4>
        <p>Choose from pen, highlighter, shapes, eraser, or color picker tools.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Draw on Your Screen</h4>
        <p>Click and drag to draw on the shared screen. All participants will see your annotations in real-time.</p>
    </div>
</div>

<h3>Remote Control Feature</h3>

<p>Allow a trusted participant to control your screen while you collaborate:</p>
<ol>
    <li>While sharing, enable "Allow Remote Control"</li>
    <li>A participant can request control</li>
    <li>You'll see a prompt to approve or deny their request</li>
    <li>Once approved, they can use your mouse and keyboard</li>
    <li>You can revoke control at any time by pressing Escape</li>
</ol>

<div class="guides-warning-box">
    <strong>⚠️ Security Note:</strong> Only enable remote control with trusted participants.
</div>

<h3>Best Practices for Screen Sharing</h3>
<ul>
    <li>Close unnecessary browser tabs and applications</li>
    <li>Disable notifications to avoid interruptions</li>
    <li>Increase text size on your screen (easier to read)</li>
    <li>Move your mouse slowly and deliberately</li>
    <li>Pause frequently to let people absorb information</li>
</ul>

