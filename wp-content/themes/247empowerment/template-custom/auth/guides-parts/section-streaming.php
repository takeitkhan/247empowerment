<!-- STREAM TO YOUTUBE -->
<h2 id="stream-youtube">📺 How to Stream to YouTube</h2>

<p>Stream your meetings directly to YouTube to reach a wider audience. This guide walks you through setting up and managing your live stream.</p>

<div class="guides-info-box">
    <strong>💡 Tip:</strong> You'll need a YouTube channel to stream. You can create one for free if you don't have one already.
</div>

<h3>Before You Start</h3>

<div class="guides-warning-box">
    <strong>⚠️ Requirements:</strong>
    <ul>
        <li>A YouTube channel (free or paid)</li>
        <li>Enabled Live Streaming feature on your YouTube channel (may take 24 hours)</li>
        <li>Admin or organizer role in the meeting</li>
        <li>Stable internet connection (at least 2.5 Mbps upload speed)</li>
    </ul>
</div>

<h4>Enable Live Streaming on YouTube</h4>
<ol>
    <li>Go to <strong>youtube.com</strong> and sign into your account</li>
    <li>Click your profile icon and select <strong>"Create a channel"</strong> if you don't have one</li>
    <li>Go to <strong>Studio</strong> (top menu)</li>
    <li>Select <strong>"Create"</strong> → <strong>"Go live"</strong></li>
    <li>Follow the setup process to enable live streaming</li>
    <li><strong>Note:</strong> YouTube may require 24-48 hours to enable this feature for new channels</li>
</ol>

<!-- STREAM SETUP -->
<h2 id="stream-setup">⚙️ Connect Your YouTube Account & Setup</h2>

<h3>Connect YouTube Account</h3>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Open Meeting Settings</h4>
        <p>While creating or editing a meeting, scroll to the "Streaming" section.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Click "Connect YouTube Account"</h4>
        <p>Select YouTube as your streaming platform and click the connect button.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Authorize Access</h4>
        <p>You'll be redirected to YouTube to authorize the platform. Sign in with your YouTube account and grant permission to stream.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">4</div>
    <div class="guides-step-content">
        <h4>Select Your Channel</h4>
        <p>If you manage multiple YouTube channels, select the one where you want to stream.</p>
    </div>
</div>

<h3>Configure Stream Settings</h3>

<div class="guides-step">
    <div class="guides-step-number">5</div>
    <div class="guides-step-content">
        <h4>Set Stream Title & Description</h4>
        <p>Enter a descriptive title for your stream (e.g., "Q1 Marketing Strategy Discussion"). Add a description to help viewers understand the content.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">6</div>
    <div class="guides-step-content">
        <h4>Choose Stream Visibility</h4>
        <p>Select how the stream appears on YouTube:</p>
        <ul>
            <li><strong>Public:</strong> Anyone can find and watch</li>
            <li><strong>Unlisted:</strong> Only people with the link can watch</li>
            <li><strong>Private:</strong> Only people you invite can watch</li>
        </ul>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">7</div>
    <div class="guides-step-content">
        <h4>Add Thumbnail & Tags (Optional)</h4>
        <p>Upload a custom thumbnail and add relevant tags to help viewers discover your stream.</p>
    </div>
</div>

<h3>Start Streaming</h3>

<div class="guides-step">
    <div class="guides-step-number">8</div>
    <div class="guides-step-content">
        <h4>Begin Your Meeting</h4>
        <p>Start the meeting as usual by clicking "Join Room" or having participants join through invitations.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">9</div>
    <div class="guides-step-content">
        <h4>Enable Streaming</h4>
        <p>Once everyone is in the meeting, click the "Go Live" or "Start Streaming" button in the meeting toolbar.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">10</div>
    <div class="guides-step-content">
        <h4>Share Stream Link</h4>
        <p>A YouTube stream link will be generated. You can share this with people who want to watch the live stream.</p>
    </div>
</div>

<div class="guides-success-box">
    <strong>🔴 LIVE!</strong> Your stream is now live on YouTube. The red indicator shows your stream is active.
</div>

<!-- DURING STREAM -->
<h2 id="stream-during">📡 During Your Stream</h2>

<h3>Monitoring Your Stream Quality</h3>
<ul>
    <li>Check the stream health indicator in the meeting control panel</li>
    <li>Look for any warnings about bitrate or connection issues</li>
    <li>Monitor YouTube's live dashboard in a separate tab if needed</li>
</ul>

<h3>Interacting with Viewers</h3>
<ul>
    <li>YouTube chat is separate from your meeting chat</li>
    <li>Viewers can comment on YouTube; this doesn't appear in your meeting</li>
    <li>You can see viewer count in real-time on YouTube's dashboard</li>
    <li>Read YouTube chat by opening the YouTube live dashboard</li>
</ul>

<h3>Best Practices During Stream</h3>
<ul>
    <li>Ensure good lighting and a professional background</li>
    <li>Speak clearly and maintain a steady pace</li>
    <li>Let viewers know they can ask questions in the chat</li>
    <li>Take breaks every 30-45 minutes for longer streams</li>
    <li>Have a co-host monitor YouTube chat while you present</li>
</ul>

<div class="guides-info-box">
    <strong>💡 Tip:</strong> For professional streams, test everything beforehand with a private or unlisted stream to ensure audio/video quality is good.
</div>

<h3>Technical Settings for Optimal Streaming</h3>

<h4>Video Quality Settings</h4>
<ul>
    <li><strong>Resolution:</strong> 1080p (1920x1080) for best quality</li>
    <li><strong>Frame Rate:</strong> 30 fps is standard, 60 fps for fast-moving content</li>
    <li><strong>Bitrate:</strong> 4-8 Mbps recommended for YouTube streaming</li>
</ul>

<h4>Audio Settings</h4>
<ul>
    <li><strong>Sample Rate:</strong> 48 kHz is standard for streaming</li>
    <li><strong>Bitrate:</strong> 128 kbps recommended for clear audio</li>
    <li>Use headphones to avoid audio feedback</li>
    <li>Test audio levels before going live</li>
</ul>

<!-- AFTER STREAM -->
<h2 id="stream-after">✅ After Your Stream</h2>

<h3>End Streaming</h3>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Stop the Stream</h4>
        <p>Click the "Stop Streaming" button in the meeting toolbar when you're ready to end the stream.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Confirm Ending</h4>
        <p>A confirmation dialog will appear. Click "End Stream" to confirm. The meeting will continue without streaming.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Check YouTube</h4>
        <p>The stream will be saved to your YouTube channel. You can edit the description, add chapters, and set premiere options.</p>
    </div>
</div>

<h3>YouTube Stream Analytics</h3>
<ul>
    <li>View how many people watched your stream</li>
    <li>See viewer retention and engagement metrics</li>
    <li>Check comments and interactions from viewers</li>
    <li>Access the archive for editing or sharing</li>
</ul>

<h3>Share Your Stream</h3>
<ul>
    <li>The stream remains on YouTube and is saved as a video</li>
    <li>You can share the YouTube link on social media</li>
    <li>Embed the video on your website</li>
    <li>Download the video for archival purposes</li>
</ul>

<div class="guides-info-box">
    <strong>💡 Tip:</strong> YouTube keeps your stream archive for up to 12 hours for testing. Save important streams to your channel permanently.
</div>

<h3>Post-Stream Optimization</h3>

<h4>Edit Video Details</h4>
<ol>
    <li>Go to YouTube Studio</li>
    <li>Find your stream video in the Content section</li>
    <li>Click to edit title, description, tags, and thumbnail</li>
    <li>Add timestamps to help viewers navigate</li>
</ol>

<h4>Add Chapters to Your Video</h4>
<p>Help viewers navigate your stream by adding chapters in the description:</p>
<pre><code>0:00 Introduction
5:30 Topic 1: Key Points
15:20 Q&A Session
20:45 Conclusion
</code></pre>

<h4>Create a Playlist</h4>
<ul>
    <li>Group related streams together for easy viewing</li>
    <li>Share the playlist link to reach a wider audience</li>
    <li>Help viewers discover related content</li>
</ul>

<!-- TROUBLESHOOTING STREAMING -->
<h2 id="stream-troubleshooting">🔧 Troubleshooting Streaming Issues</h2>

<h3>Stream Won't Start</h3>
<ul>
    <li>Verify YouTube channel has live streaming enabled (24-48 hour wait for new channels)</li>
    <li>Check internet connection speed (need at least 2.5 Mbps upload)</li>
    <li>Try disconnecting and reconnecting YouTube account</li>
    <li>Refresh the browser and try again</li>
</ul>

<h3>Poor Stream Quality</h3>

<div class="guides-step">
    <div class="guides-step-number">1</div>
    <div class="guides-step-content">
        <h4>Check Upload Speed</h4>
        <p>Use speedtest.net to verify you have sufficient upload bandwidth (min 2.5 Mbps, better: 5+ Mbps).</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">2</div>
    <div class="guides-step-content">
        <h4>Reduce Streaming Quality</h4>
        <p>Lower video resolution or frame rate in meeting settings if experiencing issues.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">3</div>
    <div class="guides-step-content">
        <h4>Close Bandwidth Hogs</h4>
        <p>Close file-sharing apps, stop downloads, and pause cloud syncs during streaming.</p>
    </div>
</div>

<div class="guides-step">
    <div class="guides-step-number">4</div>
    <div class="guides-step-content">
        <h4>Improve Connection</h4>
        <p>Move closer to router or use a wired Ethernet connection for more stable streaming.</p>
    </div>
</div>

<h3>Stream Keeps Disconnecting</h3>
<ul>
    <li>Restart your internet connection</li>
    <li>Check for network interference (WiFi channel congestion)</li>
    <li>Use an Ethernet cable for more stable connection</li>
    <li>Reduce number of active participants if very high</li>
    <li>Check YouTube's system status page for any outages</li>
</ul>

<h3>Stream Not Appearing on YouTube</h3>
<ul>
    <li>Check that live streaming is enabled on your YouTube channel</li>
    <li>Verify you clicked "Start Streaming" in the meeting</li>
    <li>Allow a few seconds for the stream to appear on YouTube</li>
    <li>Check YouTube's live dashboard directly for the stream</li>
    <li>Clear browser cache and refresh YouTube page</li>
</ul>

<h3>Audio Issues During Stream</h3>

<h4>No Audio or Very Quiet</h4>
<ul>
    <li>Check microphone is selected and not muted in meeting settings</li>
    <li>Verify microphone permissions in browser</li>
    <li>Test microphone in system settings</li>
    <li>Increase microphone volume in system settings</li>
    <li>Use a higher quality microphone or USB headset</li>
</ul>

<h4>Audio Feedback or Echo</h4>
<ul>
    <li>Switch from speakers to headphones</li>
    <li>Move microphone away from speakers</li>
    <li>Lower speaker volume during streaming</li>
    <li>Ask participants to mute if they have their audio echoing</li>
</ul>

<h3>Video Freezing or Stuttering</h3>
<ul>
    <li>Check CPU usage - close background applications</li>
    <li>Lower video resolution in stream settings</li>
    <li>Reduce number of participants with video enabled</li>
    <li>Use a wired internet connection instead of WiFi</li>
    <li>Restart the streaming</li>
</ul>

<h3>YouTube Live Dashboard Issues</h3>

<h4>Can't See Live Dashboard</h4>
<ul>
    <li>Make sure you're logged into YouTube with the correct account</li>
    <li>Go to youtube.com/live/manage to access live dashboard</li>
    <li>Check if JavaScript is enabled in your browser</li>
    <li>Try a different browser</li>
</ul>

<h4>Chat Not Working</h4>
<ul>
    <li>Refresh the YouTube live dashboard page</li>
    <li>Check if live chat is enabled for your stream</li>
    <li>Verify you have permissions to moderate chat</li>
    <li>Clear browser cache and cookies</li>
</ul>

<h2>Advanced Streaming Tips</h2>

<h3>Setting Up Multiple Bitrate Streaming</h3>
<p>For professional quality, consider using OBS (Open Broadcaster Software) with adaptive bitrate:</p>
<ul>
    <li>Download OBS Studio (free and open source)</li>
    <li>Configure YouTube RTMP stream key in OBS</li>
    <li>Set up scenes and source layouts in OBS</li>
    <li>Start OBS stream before your meeting</li>
</ul>

<h3>Using Custom Overlays</h3>
<p>Enhance your stream with branded overlays:</p>
<ul>
    <li>Add logos and channel branding</li>
    <li>Include text with session title or speaker name</li>
    <li>Display call-to-action messages</li>
    <li>Show social media handles or website</li>
</ul>

<h3>Scheduling Premiere Events</h3>
<ul>
    <li>YouTube allows you to schedule stream premieres</li>
    <li>Viewers can watch together at a scheduled time</li>
    <li>Create anticipation and community engagement</li>
    <li>Works with both live and pre-recorded content</li>
</ul>

<div class="guides-warning-box">
    <strong>⚠️ Important:</strong> Always test your stream setup with a private or unlisted stream first before going public to ensure everything works properly.
</div>

<h3>Legal & Compliance Considerations</h3>

<h4>Recording Disclosures</h4>
<ul>
    <li>Notify all participants that the stream will be recorded</li>
    <li>Include recording notice in meeting invitations</li>
    <li>Some jurisdictions require explicit written consent</li>
    <li>Consult local laws regarding recording and streaming</li>
</ul>

<h4>Copyright & Music</h4>
<ul>
    <li>YouTube may flag copyrighted music in your stream</li>
    <li>Use royalty-free music or YouTube Audio Library</li>
    <li>Avoid playing full songs during stream</li>
    <li>Read YouTube's copyright policies before streaming</li>
</ul>

